"""Deep dive on the 1809-1811 neutral-carrier boom (Yankees in the Sound).

Answers four questions, all numbers generated by this script:
  Q1. Boom-era cargo mix: naval stores vs colonial re-exports vs ballast,
      comparing certain US voyages across 1783-1800 / 1801-1808 / 1809-1811.
  Q2. To/evenningen transit port: US voyages touching To/evenningen (all clerk spellings),
      by period, plus all-traffic context.
  Q3. Captain continuity: how many 1809-1811 captains (name+domicile) had
      sailed before 1807? Old hands vs new entrants.
  Q4. Direction structure: US->Baltic / Baltic->US / intra-European shares,
      boom vs earlier periods.

Caveats baked in: domicile is the captain's stated residence, debated as a
proxy for ship registry (sc_source.pdf n.3); cargoes under-reported via
smuggling (figures are lower bounds); departure/destination are the declared
legs around the Sound passage, not full voyages; To/evenningen variants matched
exactly (no guessing), one note-style entry excluded.

Outputs: notes/boom_cargo_categories.csv, notes/boom_cargo_periods.csv,
         notes/boom_toenningen.csv, notes/boom_captains.csv,
         notes/boom_captains_list.csv, notes/boom_direction.csv
"""
import pandas as pd
import re
import sys
sys.path.insert(0, 'analysis')
from identify_us import us_voyages, is_certain_us_port

PERIODS = [('1783-1800', 1783, 1800), ('1801-1808', 1801, 1808), ('1809-1811', 1809, 1811)]

# ---------------------------------------------------------------- commodity categories
# Only commodities confidently glossed in cargo_analysis.py are mapped.
# Danish originals kept everywhere; anything unmapped -> 'other'.
# Dyewoods: New-World dyewoods are colonial re-exports. Contemporary Danish/
# Norwegian trade vocabulary equates blauholt = campecheholt = logwood
# (Knudtzon, "Increased Imports of Colorants...", Heritage 2022, 5(4),
# DOI 10.3390/heritage5040193); brasil-/sandel-holt are the analogous
# brazilwood/sandalwood dyewoods; gelbholt is fustic (yellow dyewood);
# farvetræ/farve træ is generic "dye wood".
# STOKFISHOLT: Grimm DWB s.v. "stockfischholz" defines it as Rotholz for
# dyeing, "thin, of lesser quality (lean as a stockfish)" -- the name is
# metaphorical (wood shaped like dried cod), not literal fish. See
# https://www.dwds.de/wb/dwb/stockfischholz. Stokf. holt / Stokfiskholt and
# variants are therefore counted as dyewoods. Pure fish entries (Stokfisk
# without holt/træ) remain 'other'.
# Matched by stem+wood regex over observed spellings (Camp. holt,
# Campecheholt, Blauholt, Brasilienholt, Gelbholt, Farvetræ, Stokf. holt,
# Stokfiskholt, ...).
NAVAL_STORES = {'Hamp', 'Hør', 'Stang jern', 'Stangjern', 'St. jern', 'Jern',
                'Staal', 'Sejldug', 'Seildug', 'Seyldug', 'Syldug',
                'Ravndug', 'Ravendug', 'Ravndug etc.', 'Ravendug etc',
                'Tjære', 'Beg', 'Tougværk', 'Tømmer', 'Træ', 'Trælast'}
# Dreil/Dreyl (drill/ticking, a linen fabric) removed from naval stores --
# it is a textile, not a naval store. Now 'other' pending better gloss.
# US DOMESTIC PRODUCE vs TRUE RE-EXPORTS (reviewer point 3):
# Cotton, rice, tobacco, rum, indigo are American domestic produce, NOT re-exports.
# True re-exports: coffee, sugar, tea, pepper, dyewoods (colonial goods
# transshipped through US ports).
US_DOMESTIC = {'Bomuld', 'Riis', 'Tobak', 'Rum', 'Indigo'}
TRUE_REEXPORT = {'Kaffe', 'Caffe', 'Sukker', 'Sucker', 'The', 'Peber'}
GRAIN = {'Rug', 'Byg', 'Hvede', 'Havre', 'Ærter', 'Bønner', 'Malt'}
DYEWOOD_STEM = re.compile(r'camp|bras|blau|sandel|gelb|farve|stokf', re.I)
WOOD_WORD = re.compile(r'holt|træ|trae', re.I)


def cat_of(commodity):
    if commodity == 'Ballast':
        return 'ballast'
    if commodity in NAVAL_STORES:
        return 'naval_stores'
    if commodity in US_DOMESTIC:
        return 'us_domestic'
    if commodity in TRUE_REEXPORT:
        return 'true_reexport'
    if DYEWOOD_STEM.search(commodity) and WOOD_WORD.search(commodity):
        return 'dyewood'          # New-World dyewoods = colonial re-export
    if commodity in GRAIN:
        return 'grain'
    return 'other'


# ---------------------------------------------------------------- Q2 To/evenningen variants
# Hand-checked in departure.csv/destination.csv (all rows). Exact matches only.
# One note-style entry "Tønningen indkommen Kragerøe" deliberately excluded.
TOENNINGEN = {'tønningen', 'tønning', 'tøningen', 'tønningenn', 'tøning', 'tøninge'}


def is_toenningen(port):
    if not isinstance(port, str):
        return False
    return port.strip().lower().rstrip('.') in TOENNINGEN


REGION_PORTS = {'østersøen', 'sundet'}


def port_class(port):
    """'us' | 'europe' | 'region' | 'unknown'"""
    if not isinstance(port, str) or not port.strip():
        return 'unknown'
    if is_certain_us_port(port):
        return 'us'
    if port.strip().lower() in REGION_PORTS:
        return 'region'
    return 'europe'


def first_port(df, col):
    """First departure/destination record per ce_id (cargo-row level file)."""
    return df.sort_values('cargo_id').drop_duplicates('ce_id', keep='first')[
        ['ce_id', col]].rename(columns={col: 'port'})


def main():
    us = us_voyages(tiers=('certain',))          # certain tier = main series
    us['period'] = pd.cut(us['year'],
                          bins=[1782, 1800, 1808, 1811],
                          labels=['1783-1800', '1801-1808', '1809-1811'])
    ce = pd.read_csv('data/customs_entries.csv', sep=';',
                     usecols=['ce_id', 'year'])
    year_of = dict(zip(ce['ce_id'], ce['year']))

    print('=== certain US voyages by period (1812-1815 excluded by design) ===')
    print(us['period'].value_counts().sort_index().to_string())

    # ================= Q1: cargo mix by period =================
    print('\n=== Q1 cargo ===')
    c = pd.read_csv('data/cargoes_regs.csv', sep=';', usecols=['ce_id', 'commodity'])
    c_us = c[c['ce_id'].isin(set(us['ce_id']))].copy()
    # period from the us frame itself (single source of truth for ce_id->year);
    # 1812-1815 voyages excluded by design (not in any of the three periods)
    ce_period = dict(zip(us['ce_id'], us['period'].astype(str)))
    c_us['period'] = c_us['ce_id'].map(ce_period)
    vp = c_us.drop_duplicates(['ce_id', 'commodity']).copy()
    vp['cat'] = vp['commodity'].map(cat_of)

    rows, top_rows = [], []
    for p, lo, hi in PERIODS:
        sub = us[us['period'] == p]
        n_voy = sub['ce_id'].nunique()
        vps = vp[vp['period'] == p]
        n_cargo = vps['ce_id'].nunique()
        rec = {'period': p, 'voyages': n_voy, 'voyages_with_cargo': n_cargo}
        for cat in ('naval_stores', 'us_domestic', 'true_reexport', 'dyewood',
                    'ballast', 'grain'):
            n = vps[vps['cat'] == cat]['ce_id'].nunique()
            rec[f'{cat}_voyages'] = n
            rec[f'{cat}_pct'] = round(n / n_cargo * 100, 1) if n_cargo else 0.0
        # true re-exports incl. dyewoods (dyewoods are New-World re-exports)
        n_ct = vps[vps['cat'].isin(('true_reexport', 'dyewood'))]['ce_id'].nunique()
        rec['reexport_total_voyages'] = n_ct
        rec['reexport_total_pct'] = round(n_ct / n_cargo * 100, 1) if n_cargo else 0.0
        rows.append(rec)
        t = vps['commodity'].value_counts().head(15)
        for k, v in t.items():
            top_rows.append({'period': p, 'commodity': k,
                             'category': cat_of(k), 'voyages': int(v),
                             'pct': round(v / n_cargo * 100, 1) if n_cargo else 0.0})
        # both naval and domestic/reexport on same voyage (mixed cargo)
        n_both = vps[vps['cat'].isin(('naval_stores', 'us_domestic',
                                       'true_reexport'))].groupby(
            'ce_id')['cat'].nunique()
        n_both = int((n_both >= 2).sum())
        rows[-1]['mixed_cargo_voyages'] = n_both
        print(f"{p}: voyages={n_voy} with_cargo={n_cargo} "
              f"naval={rec['naval_stores_pct']}% us_domestic={rec['us_domestic_pct']}% "
              f"true_reexport={rec['true_reexport_pct']}% dyewood={rec['dyewood_pct']}% "
              f"reexport_total={rec['reexport_total_pct']}% "
              f"ballast={rec['ballast_pct']}% mixed={n_both}")
    pd.DataFrame(rows).to_csv('notes/boom_cargo_categories.csv', index=False)
    pd.DataFrame(top_rows).to_csv('notes/boom_cargo_periods.csv', index=False)

    # unmapped-commodity sanity check for the boom period
    boom_vp = vp[vp['period'] == '1809-1811']
    unmapped_share = (boom_vp['cat'] == 'other').mean() * 100
    print(f"boom-period cargo rows in 'other': {unmapped_share:.1f}% "
          f"(of {len(boom_vp)} voyage-commodity pairs)")

    # ================= Q2: To/evenningen =================
    print('\n=== Q2 To/evenningen ===')
    dep = first_port(pd.read_csv('data/departure.csv', sep=';', usecols=['cargo_id', 'ce_id', 'departure']), 'departure')
    dst = first_port(pd.read_csv('data/destination.csv', sep=';', usecols=['cargo_id', 'ce_id', 'destination']), 'destination')
    legs = dep.merge(dst, on='ce_id', suffixes=('_dep', '_dst'))
    legs['year'] = legs['ce_id'].map(year_of)
    legs['tonn_dep'] = legs['port_dep'].map(is_toenningen)
    legs['tonn_dst'] = legs['port_dst'].map(is_toenningen)

    trows = []
    for p, lo, hi in PERIODS:
        us_ids = set(us[us['period'] == p]['ce_id'])
        l_us = legs[legs['ce_id'].isin(us_ids)]
        l_all = legs[(legs['year'] >= lo) & (legs['year'] <= hi)]
        rec = {
            'period': p,
            'us_voyages': len(l_us),
            'us_tonn_dep': int(l_us['tonn_dep'].sum()),
            'us_tonn_dst': int(l_us['tonn_dst'].sum()),
            'us_tonn_either': int((l_us['tonn_dep'] | l_us['tonn_dst']).sum()),
            'all_voyages': len(l_all),
            'all_tonn_either': int(((l_all['tonn_dep']) | (l_all['tonn_dst'])).sum()),
        }
        rec['us_tonn_pct'] = round(rec['us_tonn_either'] / rec['us_voyages'] * 100, 1) if rec['us_voyages'] else 0
        rec['all_tonn_pct'] = round(rec['all_tonn_either'] / rec['all_voyages'] * 100, 2) if rec['all_voyages'] else 0
        trows.append(rec)
        print(f"{p}: US {rec['us_tonn_either']}/{rec['us_voyages']} "
              f"({rec['us_tonn_pct']}%) dep={rec['us_tonn_dep']} dst={rec['us_tonn_dst']} | "
              f"all traffic {rec['all_tonn_either']}/{rec['all_voyages']} ({rec['all_tonn_pct']}%)")
    pd.DataFrame(trows).to_csv('notes/boom_toenningen.csv', index=False)

    # ================= Q3: captain continuity =================
    print('\n=== Q3 captains ===')
    dmap = pd.read_csv('notes/us_domicile_dictionary.csv')
    dom_norm = {r['domicile_raw'].strip().lower(): r['normalized_port']
                for _, r in dmap.iterrows()}


    def norm_dom(d):
        if not isinstance(d, str):
            return ''
        return dom_norm.get(d.strip().lower(), d.strip().lower())


    def norm_name(x):
        return x.strip().lower() if isinstance(x, str) else ''


    cap = us[['ce_id', 'firstName', 'lastName', 'domicile', 'year', 'period']].copy()
    cap['fn'] = cap['firstName'].map(norm_name)
    cap['ln'] = cap['lastName'].map(norm_name)
    cap['dom'] = cap['domicile'].map(norm_dom)
    cap['key_strict'] = cap['fn'] + '|' + cap['ln'] + '|' + cap['dom']
    cap['key_loose'] = cap['fn'] + '|' + cap['ln']

    boom_keys = set(cap[cap['period'] == '1809-1811']['key_strict'])
    boom_keys = {k for k in boom_keys if not k.startswith('|')}
    pre_keys = set(cap[cap['year'] <= 1806]['key_strict'])
    continuing = boom_keys & pre_keys
    new = boom_keys - pre_keys
    # loose upper bound: same name regardless of domicile spelling/change
    boom_loose = {k for k in set(cap[cap['period'] == '1809-1811']['key_loose']) if not k.startswith('|')}
    pre_loose = set(cap[cap['year'] <= 1806]['key_loose'])
    continuing_loose = boom_loose & pre_loose

    print(f"boom captains (name+domicile, strict): {len(boom_keys)}")
    print(f"  also sailed <=1806: {len(continuing)} ({len(continuing)/len(boom_keys)*100:.1f}%)")
    print(f"  new entrants: {len(new)} ({len(new)/len(boom_keys)*100:.1f}%)")
    print(f"loose name-only match: {len(continuing_loose)}/{len(boom_loose)} continuing")

    clist = []
    for k in sorted(boom_keys):
        fn, ln, dom = k.split('|')
        n_boom = int(((cap['key_strict'] == k) & (cap['period'] == '1809-1811')).sum())
        n_pre = int(((cap['key_strict'] == k) & (cap['year'] <= 1806)).sum())
        clist.append({'captain': f"{fn} {ln}", 'domicile_norm': dom,
                      'boom_voyages': n_boom, 'pre1807_voyages': n_pre,
                      'continuing': k in continuing})
    pd.DataFrame(clist).to_csv('notes/boom_captains_list.csv', index=False)
    pd.DataFrame([{
        'metric': 'boom_captains_strict', 'value': len(boom_keys)},
        {'metric': 'continuing_pre1807_strict', 'value': len(continuing)},
        {'metric': 'continuing_pct_strict',
         'value': round(len(continuing) / len(boom_keys) * 100, 1)},
        {'metric': 'new_entrants_strict', 'value': len(new)},
        {'metric': 'continuing_loose_name_only', 'value': len(continuing_loose)},
        {'metric': 'boom_captains_loose', 'value': len(boom_loose)},
    ]).to_csv('notes/boom_captains.csv', index=False)

    # ================= Q4: direction structure =================
    print('\n=== Q4 direction ===')
    legs_us = legs[legs['ce_id'].isin(set(us['ce_id']))].copy()
    legs_us['period'] = legs_us['year'].apply(
        lambda y: '1783-1800' if y <= 1800 else ('1801-1808' if y <= 1808
                                                else ('1809-1811' if y <= 1811 else 'other')))
    legs_us['dep_c'] = legs_us['port_dep'].map(port_class)
    legs_us['dst_c'] = legs_us['port_dst'].map(port_class)


    def direction(r):
        d, s = r['dep_c'], r['dst_c']
        if d == 'unknown' or s == 'unknown':
            return 'unknown'
        if d == 'region' or s == 'region':
            return 'involving_region'
        if d == 'us' and s == 'europe':
            return 'US_to_Europe'
        if d == 'europe' and s == 'us':
            return 'Europe_to_US'
        if d == 'europe' and s == 'europe':
            return 'intra_Europe'
        if d == 'us' and s == 'us':
            return 'US_to_US'
        return 'other'


    legs_us['direction'] = legs_us.apply(direction, axis=1)
    drows = []
    for p, lo, hi in PERIODS:
        sub = legs_us[legs_us['period'] == p]
        n = len(sub)
        vc = sub['direction'].value_counts()
        rec = {'period': p, 'voyages': n}
        for d_ in ('US_to_Europe', 'Europe_to_US', 'intra_Europe', 'US_to_US',
                   'involving_region', 'unknown'):
            rec[d_] = int(vc.get(d_, 0))
            rec[d_ + '_pct'] = round(vc.get(d_, 0) / n * 100, 1) if n else 0
        drows.append(rec)
        print(f"{p} (n={n}): " + ' '.join(
            f"{d_}={rec[d_ + '_pct']}%" for d_ in
            ('US_to_Europe', 'Europe_to_US', 'intra_Europe', 'involving_region', 'unknown')))
    pd.DataFrame(drows).to_csv('notes/boom_direction.csv', index=False)

    # sanity: which 'europe' ports dominate boom departures (top 10, raw names)
    boom = legs_us[legs_us['period'] == '1809-1811']
    print('\nboom top departures (raw):')
    print(boom['port_dep'].value_counts().head(10).to_string())
    print('\nboom top destinations (raw):')
    print(boom['port_dst'].value_counts().head(10).to_string())


if __name__ == '__main__':
    main()
